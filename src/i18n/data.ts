/**
 * Katalógus-, stílus- és receptadatok fordításai azonosító szerint.
 * Tömör forma: [leírás] vagy [leírás, név].
 */
type Entry = { name?: string; desc?: string };
type Tuple = [desc: string, name?: string];
export interface DataDict {
  malts: Record<string, Entry>;
  hops: Record<string, Entry>;
  yeasts: Record<string, Entry>;
  adjuncts: Record<string, Entry>;
  styles: Record<string, Entry>;
  presets: Record<string, Entry>;
}
const build = (o: Record<string, Tuple>): Record<string, Entry> =>
  Object.fromEntries(Object.entries(o).map(([k, [desc, name]]) => [k, name ? { desc, name } : { desc }]));

